-- Use normal Run mode. This script waits until the independent window is dismissed.
-- nil selects the current threadId as the title. Omitting button shows only OK.
print("Before message")
local accepted = ui.message(nil, "Hello from UniComm!\nOK/Enter returns true; Escape or closing returns false.")
print("Accepted:", accepted)
print("After message")

---

-- A custom title and two standard buttons. Only an explicit acceptance is true.
local confirmed = ui.message("Confirm", "Do you want to continue?", {"ok", "cancel"})
if confirmed then
    print("Confirmed")
else
    print("Cancelled")
end

---

-- A single-line input. An empty string means OK with no text, not cancellation.
local name = ui.input(nil, "Enter a name", "UniComm")
if name == nil then
    print("Input cancelled")
else
    print("Name:", name)
end

---

-- Input always returns text. Convert numbers in Lua after checking cancellation.
local value = ui.input("Parameter", "Enter the target temperature", "25")
if value ~= nil then
    local temperature = tonumber(value)
    if temperature == nil then
        print("Not a number:", value)
    else
        print("Temperature:", temperature)
    end
end

